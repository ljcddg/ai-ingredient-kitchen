-- ============================================================
-- 食材主数据扩充（第三批，id 189~252，共 64 种）
-- 与 frontend-vue/src/lib/ingredients.js 一一对应 —— 那边点选传的就是这些 id。
-- ============================================================
-- 【为什么要有这一批】
-- 前两批 88 种覆盖了"家常炒菜"，但用户最容易卡住的场景其实是：
--   ① 想做点不一样的（苦瓜、秋葵、芦笋、丝瓜），前端根本没有，只能手输；
--   ② 手输的自由食材没有主数据 ID，进不了营养汇总，也进不了替代建议。
-- 所以这批挑的是"菜市场每天都有、但库里没有"的品类，而不是猎奇食材。
--
-- 【id 分配原则】
-- 189 起顺延，按"蔬菜 → 肉类 → 水产 → 豆制品 → 主食 → 调料 → 乳品果香"排，
-- 组内大致按日常出现频率降序。**不要跳号复用**：前端 hardcode 了 id，
-- 一旦某个 id 的语义变了，用户的收藏/历史记录会指向另一个食材。
--
-- 【数据来源说明】
-- 每 100g 营养值仍是**常见食物成分参考值**（《中国食物成分表》量级），
-- 用途与前两批一致：① 前端分类展示 ② 后台按 40% 偏差阈值校验 AI 给的营养。
-- 精度要求是"量级正确即可"；要当用户可见的精确营养，必须先换权威数据表。
--
-- ⚠️ 调料组同样注意：盐/酱油/鸡精的 sodium 是每 100g 上万毫克，这是正常的，
--    它们绝不能按"食材用量"参与营养汇总（见 IngredientResolver 的调料白名单）。
-- ============================================================


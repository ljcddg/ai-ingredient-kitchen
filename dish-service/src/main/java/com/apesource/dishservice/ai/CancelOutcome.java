package com.apesource.dishservice.ai;

/**
 * 取消任务的结果。
 *
 * <p>为什么不用 boolean：调用方需要区分「取消成功」和「本来就不该让你取消」，
 * 前者可以提示"已取消"，后者要提示"这不是你的任务"，用 boolean 就没法区分了。
 */
public enum CancelOutcome {

    /**
     * 任务还在排队，已从队列里移除 —— <b>这种取消是真省资源</b>，因为压根没开始跑。
     */
    CANCELLED_WAITING,

    /**
     * 任务正在执行，已打上取消标记并中断线程 —— 这是<b>逻辑取消</b>。
     *
     * <p>注意：{@code Future.cancel(true)} 只是给线程打中断标志，
     * 底层阻塞中的 HTTP 请求<b>不一定会真的停下来</b>，资源可能还要等这一轮跑完。
     * 要做到"执行中也能立刻省资源"，得改用流式调用 + 在回调里检查中断标志，
     * 那是后续的优化项（用户已确认第一版不做）。
     */
    CANCELLED_RUNNING,

    /** 任务不属于当前用户 —— 队列权限规则：只能管理自己的任务 */
    NOT_OWNER,

    /** 队列里找不到它（可能已经执行完、已经取消过、或根本没提交成功） */
    NOT_FOUND
}

/** 把毫秒数说成人话：12.3 秒 / 1 分 05 秒 */
export function humanDuration(ms) {
  if (!ms && ms !== 0) return ''
  const sec = Math.round(ms / 1000)
  if (sec < 60) return sec + ' 秒'
  const m = Math.floor(sec / 60)
  const s = sec % 60
  return m + ' 分 ' + (s < 10 ? '0' + s : s) + ' 秒'
}
